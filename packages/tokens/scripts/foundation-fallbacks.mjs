// Writes src/fallbacks.mjs: a metric-matched local fallback for each foundation font family (engine.mjs FONTS), read
// from the Fontsource files this package depends on. A feather-tokens/4 brand that names a foundation family gets its
// fallback face, so the swap from the fallback to the real face shifts nothing (CLS). Run after changing FONTS:
//   node packages/tokens/scripts/foundation-fallbacks.mjs
import fs from "node:fs"
import path from "node:path"
import { createRequire } from "node:module"
import { FONTS, STATIC_FONT_WEIGHTS } from "../src/engine.mjs"
import { fallbackFor, fontMetrics } from "../src/fontmetrics.mjs"

const require = createRequire(import.meta.url)
const SERIF = new Set(["Fraunces", "Playfair Display"])
const out = {}
for (const [family, pkg] of Object.entries(FONTS)) {
  const dir = path.join(path.dirname(require.resolve(`${pkg}/package.json`)), "files")
  const slug = path.basename(pkg)
  const name = STATIC_FONT_WEIGHTS[family] ? `${slug}-latin-400-normal.woff2` : `${slug}-latin-wght-normal.woff2`
  const face = /\bMono\b/.test(family) ? "Courier New" : SERIF.has(family) ? "Times New Roman" : "Arial"
  out[family] = fallbackFor(fontMetrics(fs.readFileSync(path.join(dir, name))), face)
}
const file = path.join(import.meta.dirname, "../src/fallbacks.mjs")
fs.writeFileSync(
  file,
  `// Generated by scripts/foundation-fallbacks.mjs from the Fontsource files: do not edit by hand.\n// A metric-matched local fallback for each foundation family (size-adjust and the ascent, descent and line-gap\n// overrides, in percent), used by feather-tokens/4 brands.\nexport const FOUNDATION_FALLBACKS = ${JSON.stringify(out, null, 2)}\n`
)
console.log(`wrote ${path.relative(process.cwd(), file)}: ${Object.keys(out).length} families`)
